def test_engine_names_no_book():
    """Extensibility guard (architecture 7.2).

    A book identifier anywhere in the engine means the corpus has leaked into
    the reasoning layer, and adding a book would then require an engine change.
    """
    banned = ("phaladeepika", "brihat-jataka", "mantreswara", "varahamihira")
    offenders = []
    for py in (ROOT / "Engine").rglob("*.py"):
        if "tests" in py.parts:
            continue
        low = py.read_text(encoding="utf-8").lower()
        for word in banned:
            if word in low:
                offenders.append(f"{py.relative_to(ROOT)}: {word}")
    assert not offenders, offenders


