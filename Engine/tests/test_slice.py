# Astrodienst printed tables, Ephemeris/ae_2000d.pdf page 2, 1 January 2000
# 00:00 UT, tropical geocentric, truncated to whole arcminutes.
#
# Caveat worth stating: those tables are themselves generated by the Swiss
# Ephemeris (from JPL DE441). This check is therefore independent of our code
# path -- adapter, flags, ayanamsa handling, unit conversion -- but NOT
# independent of the underlying library. A genuinely independent oracle is
# still owed.
PRINTED_2000_01_01 = {
    "Sun":     270 + 9 + 51.55 / 60,
    "Moon":    210 + 7 + 18 / 60,
    "Mercury": 270 + 1 + 7 / 60,
    "Venus":   240 + 0 + 58 / 60,
    "Mars":    300 + 27 + 35 / 60,
    "Jupiter":   0 + 25 + 14 / 60,
    "Saturn":   30 + 10 + 24 / 60,
    "Rahu":    120 + 3 + 59 / 60,
}


@pytest.mark.parametrize("body,printed", sorted(PRINTED_2000_01_01.items()))
def test_matches_printed_ephemeris(provider, body, printed):
    jd = provider.julian_day_ut(2000, 1, 1, 0.0)
    ayanamsa = provider.ayanamsa(jd, "lahiri")
    tropical = (provider.body_position(jd, body, "lahiri").lon + ayanamsa) % 360.0
    arcmin = abs(((tropical - printed + 180.0) % 360.0) - 180.0) * 60.0
    assert arcmin < 1.0, f"{body}: {arcmin:.2f} arcmin from the printed table"


def test_ketu_is_exactly_opposite_rahu(provider):
    jd = provider.julian_day_ut(2000, 1, 1, 0.0)
    rahu = provider.body_position(jd, "Rahu", "lahiri").lon
    ketu = provider.body_position(jd, "Ketu", "lahiri").lon
    assert abs(((ketu - rahu) % 360.0) - 180.0) < 1e-9


def test_high_latitude_cusp_systems_refuse_rather_than_lie(provider):
    from Engine.ephemeris import EphemerisError
