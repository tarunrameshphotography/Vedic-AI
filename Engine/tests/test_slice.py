# --- determinism -------------------------------------------------------------

def test_method_note_is_stable_across_processes():
    """Regression: the note sliced NEGATION_CUES (a frozenset) before sorting.

    Set iteration order for strings varies per process, so the same chart
    rendered a different method note on every run. An in-process check cannot
    catch this -- the hash seed is fixed for the life of the interpreter -- so
    each sample must be a separate subprocess.
    """
    import subprocess
    code = (
        "from Engine.synthesis import synthesise;"
        "print(synthesise([]).method_note)"
    )
    notes = {
        subprocess.run([sys.executable, "-c", code], cwd=ROOT,
                       capture_output=True, text=True, check=True).stdout
        for _ in range(4)
    }
    assert len(notes) == 1, f"method note varies between runs: {notes}"


def test_consultation_is_byte_identical_across_processes():
    """The whole report must be reproducible, not just the parts we thought of."""
    import subprocess
    code = (
        "from Engine.chart import BirthRecord;"
        "from Engine.pipeline import run;"
        "r = run(BirthRecord(date='1987-03-14', time='04:22',"
        "  timezone='Asia/Kolkata', latitude=10.7870, longitude=79.1378,"
        "  place_name='Thanjavur', time_precision='minute',"
        "  time_source='certificate'));"
        "import hashlib;"
        "print(hashlib.sha256(r.consultation.encode('utf-8')).hexdigest())"
    )
    digests = {
        subprocess.run([sys.executable, "-c", code], cwd=ROOT,
                       capture_output=True, text=True, check=True).stdout.strip()
        for _ in range(3)
    }
    assert len(digests) == 1, f"consultation is not reproducible: {digests}"
