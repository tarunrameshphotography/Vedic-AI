# --- condition evaluator ----------------------------------------------------

def _facts(*pairs):
    frame = {"reference": "lagna", "varga": "D1", "house_system": "whole_sign"}
    return FactSet([make_fact("in_house", {"graha": g, "house": h}, frame)
                    for g, h in pairs])


def test_evaluator_matches_and_reports_bindings():
    ev = evaluate({"all": [{"in_house": {"graha": "Sun", "house": 10}}]},
                  _facts(("Sun", 10)))
    assert ev.satisfied and ev.bindings == ("in_house(Sun,10)",)


def test_evaluator_does_not_confuse_adjacent_houses():
    ev = evaluate({"all": [{"in_house": {"graha": "Mars", "house": 7}}]},
                  _facts(("Mars", 8)))
    assert not ev.satisfied


def test_all_requires_every_condition():
    cond = {"all": [{"in_house": {"graha": "Sun", "house": 10}},
                    {"in_house": {"graha": "Moon", "house": 4}}]}
    assert not evaluate(cond, _facts(("Sun", 10))).satisfied
    assert evaluate(cond, _facts(("Sun", 10), ("Moon", 4))).satisfied


def test_unknown_predicate_is_inert_never_true():
    ev = evaluate({"all": [{"exalted": {"graha": "Sun"}}]}, _facts(("Sun", 10)))
    assert not ev.satisfied and ev.missing == ("exalted",)


